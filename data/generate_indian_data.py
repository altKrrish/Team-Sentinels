def generate_indian_records_dataset(output_path: str):
    """Save the curated Indian OISD and OIL India dataset to CSV."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    fieldnames = [
        "source_reference", "incident_title", "organization",
        "location_site", "location_state", "location_area",
        "activity_type", "equipment_involved", "oisd_standard",
        "narrative", "hospitalized", "amputation", "loss_of_eye", "fatalities",
        "nature_of_injury", "part_of_body", "event_type",
        "sif_potential", "sif_potential_binary", "sif_confidence_score", "sif_rationale",
        "life_saving_rules", "barrier_type", "barrier_status", "root_cause"
    ]

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for rec in INDIAN_INCIDENT_RECORDS:
            row = rec.copy()
            row["life_saving_rules"] = "|".join(rec["life_saving_rules"]) if rec["life_saving_rules"] else "None"
            writer.writerow(row)

    print(f"✅ Generated Indian OISD & OIL Incident Dataset: {output_path} ({len(INDIAN_INCIDENT_RECORDS)} high-detail verified cases)")


